from __future__ import annotations

import json
from typing import Iterable

from .model import ProvenanceEvent


def render_json(
    events: Iterable[ProvenanceEvent],
    *,
    placebo: bool = False,
    neutral: bool = False,
    policy_only: bool = False,
) -> str:
    if sum((placebo, neutral, policy_only)) > 1:
        raise ValueError("overlay ablation modes are mutually exclusive")
    records = []
    for event in events:
        item = event.to_dict()
        if placebo:
            item["object_origins"] = tuple("unresolved" for _ in event.object_origins)
            item["authority"] = "unresolved"
            item["depends_on"] = ()
        elif neutral:
            item["authority"] = "not_evaluated"
        elif policy_only:
            item["object_origins"] = tuple("unresolved" for _ in event.object_origins)
            item["depends_on"] = ()
        records.append(item)
    return json.dumps(
        {
            "schema": "origin-guard/provenance-overlay/v1",
            "semantics": (
                "Records are generated by the trusted host from observable "
                "message and tool structure. Agent-authored content is not user "
                "authorization. Unknown origin remains unknown."
                if not placebo and not neutral and not policy_only
                else (
                    "Factual origin overlay. Authority policy is intentionally "
                    "withheld; object origins and structural dependencies remain."
                    if neutral
                    else (
                        "Authority-policy overlay. Factual object origins and "
                        "structural dependencies are intentionally withheld."
                        if policy_only
                        else "Control overlay with provenance and authority values removed."
                    )
                )
            ),
            "events": records,
        },
        indent=2,
        sort_keys=True,
    )
